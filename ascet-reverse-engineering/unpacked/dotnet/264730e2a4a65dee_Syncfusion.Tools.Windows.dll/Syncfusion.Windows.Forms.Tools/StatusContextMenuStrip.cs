using System;
using System.ComponentModel;
using System.Drawing;
using System.Globalization;
using System.Windows.Forms;

namespace Syncfusion.Windows.Forms.Tools;

[ToolboxItem(false)]
public class StatusContextMenuStrip : ContextMenuStripEx
{
	internal class StatusMenuItem : ToolStripMenuItem
	{
		private ToolStripItem m_item;

		public string Status
		{
			get
			{
				if (m_item is IStatusItem2 statusItem)
				{
					return statusItem.StatusString;
				}
				return null;
			}
		}

		public StatusMenuItem(ToolStripItem item)
		{
			base.ShowShortcutKeys = false;
			m_item = item;
			string text = item.Text;
			if (string.IsNullOrEmpty(text))
			{
				text = item.Name;
			}
			Text = text;
			if (item is IStatusItem)
			{
				IStatusItem statusItem = item as IStatusItem;
				base.Checked = statusItem.Active;
			}
			else
			{
				base.Checked = item.Available;
			}
		}

		protected override void SetBounds(Rectangle rect)
		{
			ToolStrip toolStrip = base.Owner;
			if (toolStrip != null)
			{
				Rectangle rectangle = Rectangle.Inflate(toolStrip.ClientRectangle, -1, 0);
				rect.X = rectangle.X;
				if (rect.Width < rectangle.Width)
				{
					rect.Width = rectangle.Width;
				}
			}
			base.SetBounds(rect);
		}

		protected override void OnClick(EventArgs e)
		{
			base.OnClick(e);
			if (m_item is IStatusItem)
			{
				IStatusItem statusItem = m_item as IStatusItem;
				bool active = (base.Checked = !statusItem.Active);
				statusItem.Active = active;
			}
			else
			{
				bool available = (base.Checked = !m_item.Available);
				m_item.Available = available;
			}
		}
	}

	private const int INTERNAL_PADDING = 20;

	private StatusStripEx m_header;

	private bool m_bAutoGenerated;

	internal bool AutoGenerated
	{
		get
		{
			return m_bAutoGenerated;
		}
		set
		{
			if (m_bAutoGenerated != value)
			{
				m_bAutoGenerated = value;
			}
		}
	}

	internal StatusStripEx StatusStrip
	{
		get
		{
			return m_header;
		}
		set
		{
			m_header = value;
		}
	}

	protected override Size MaxItemSize
	{
		get
		{
			Size szTarget = Size.Empty;
			Size szTarget2 = Size.Empty;
			foreach (ToolStripItem item in Items)
			{
				if (item is StatusMenuItem statusMenuItem)
				{
					MaximizeSize(ref szTarget, GetTextSize(statusMenuItem.Text));
					MaximizeSize(ref szTarget2, GetTextSize(statusMenuItem.Status));
				}
			}
			int num = szTarget.Width + base.Padding.Horizontal;
			if (szTarget2.Width > 0)
			{
				num += 20 + szTarget2.Width;
			}
			int num2 = base.ImageScalingSize.Height;
			if (num2 < szTarget.Height)
			{
				num2 = szTarget.Height;
			}
			if (num2 < szTarget2.Height)
			{
				num2 = szTarget2.Height;
			}
			num2 += base.Padding.Vertical;
			return new Size(num, num2);
		}
	}

	public StatusContextMenuStrip()
	{
	}

	public StatusContextMenuStrip(StatusStripEx statusStrip)
		: base(SR.GetString(CultureInfo.CurrentCulture, "StatusStripMenuCaption"))
	{
		StatusStrip = statusStrip;
	}

	protected override void Dispose(bool disposing)
	{
		if (disposing)
		{
			SR.ReleaseResources();
			StatusStrip = null;
		}
		base.Dispose(disposing);
	}

	protected override void OnOpening(CancelEventArgs e)
	{
		StatusStripEx statusStrip = StatusStrip;
		if (statusStrip != null)
		{
			if (base.Renderer != statusStrip.Renderer)
			{
				base.Renderer = statusStrip.Renderer;
			}
			if (AutoGenerated)
			{
				Items.Clear();
				int num = 0;
				bool flag = false;
				foreach (ToolStripItem notificationsItem in statusStrip.NotificationsItems)
				{
					if (notificationsItem is IStatusItem statusItem)
					{
						if (flag)
						{
							Items.Add(new ToolStripSeparator());
							flag = false;
						}
						num++;
						StatusMenuItem value = new StatusMenuItem(notificationsItem);
						Items.Add(value);
						if (statusItem.EndOfGroup && num != 0)
						{
							flag = true;
							num = 0;
						}
					}
				}
				if (statusStrip.StatusControlsItems.Count > 0 && statusStrip.NotificationsItems.Count > 0)
				{
					Items.Add(new ToolStripSeparator());
				}
				foreach (ToolStripItem statusControlsItem in statusStrip.StatusControlsItems)
				{
					ToolStripMenuItem value2 = new StatusMenuItem(statusControlsItem);
					Items.Add(value2);
				}
				e.Cancel = Items.Count == 0;
			}
		}
		base.OnOpening(e);
	}

	protected override void OnClosing(ToolStripDropDownClosingEventArgs e)
	{
		base.OnClosing(e);
		if (e.CloseReason == ToolStripDropDownCloseReason.ItemClicked)
		{
			e.Cancel = true;
		}
	}

	protected override void OnKeyDown(KeyEventArgs e)
	{
		Keys keyCode = e.KeyCode;
		if (keyCode == Keys.Space)
		{
			GetSelectedItem()?.PerformClick();
		}
		else
		{
			base.OnKeyDown(e);
		}
	}

	protected override void OnRendererChanged(EventArgs e)
	{
		base.OnRendererChanged(e);
	}

	private void MaximizeSize(ref Size szTarget, Size szMin)
	{
		if (szTarget.Width < szMin.Width)
		{
			szTarget.Width = szMin.Width;
		}
		if (szTarget.Height < szMin.Height)
		{
			szTarget.Height = szMin.Height;
		}
	}

	private Size GetTextSize(string text)
	{
		if (!string.IsNullOrEmpty(text))
		{
			return TextRenderer.MeasureText(text, Font);
		}
		return Size.Empty;
	}

	private ToolStripMenuItem GetSelectedItem()
	{
		int i = 0;
		for (int count = DisplayedItems.Count; i < count; i++)
		{
			ToolStripItem toolStripItem = DisplayedItems[i];
			if (toolStripItem.Selected)
			{
				return toolStripItem as ToolStripMenuItem;
			}
		}
		return null;
	}
}
