using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Windows.Forms;
using System.Windows.Forms.Design;

namespace Syncfusion.Windows.Forms.Tools;

[ToolStripItemDesignerAvailability(ToolStripItemDesignerAvailability.None)]
public class ToolStripTabItem : ToolStripButton, IToolStripTabItem, IShortcutSupport, ICustomTypeDescriptor
{
	private const int DEFAULT_PADDING = 1;

	private RibbonPanel m_panel;

	private static string[] HiddenProperties = new string[3] { "Checked", "CheckState", "CheckOnClick" };

	private bool m_bSelected;

	private bool m_bAutoGeneratedPanel;

	private bool m_bShowPanel = true;

	[Browsable(false)]
	public int Position
	{
		get
		{
			if (base.Parent is RibbonControlAdvHeader ribbonControlAdvHeader)
			{
				return ribbonControlAdvHeader.MainItems.IndexOf(this);
			}
			return -1;
		}
		set
		{
			if (Position != value && base.Parent is RibbonControlAdvHeader ribbonControlAdvHeader && Position != value)
			{
				if (ribbonControlAdvHeader.MainItems.Count <= value || value < 0)
				{
					throw new ArgumentOutOfRangeException("Position", "Position is a zero based index. Position can not be set less than zero or greater than the collection length");
				}
				OnPositionChanged(ribbonControlAdvHeader, value);
			}
		}
	}

	[DesignerSerializationVisibility(DesignerSerializationVisibility.Content)]
	public RibbonPanel Panel
	{
		get
		{
			if (m_panel == null)
			{
				m_panel = new RibbonPanel(this);
				m_bAutoGeneratedPanel = true;
			}
			return m_panel;
		}
		set
		{
			if (m_panel == value)
			{
				return;
			}
			if (m_panel != null)
			{
				if (m_bAutoGeneratedPanel)
				{
					m_panel.Dispose();
					m_bAutoGeneratedPanel = false;
				}
				else
				{
					m_panel.TabItem = null;
				}
			}
			m_panel = value;
			if (m_panel != null)
			{
				m_panel.TabItem = this;
			}
		}
	}

	public override Padding Padding
	{
		get
		{
			return base.Padding;
		}
		set
		{
			base.Padding = value;
		}
	}

	public override bool Selected => m_bSelected;

	internal bool SelectedInternal
	{
		get
		{
			return m_bSelected;
		}
		set
		{
			if (m_bSelected != value)
			{
				m_bSelected = value;
				Invalidate();
			}
		}
	}

	internal bool ShowPanel
	{
		get
		{
			return m_bShowPanel;
		}
		set
		{
			if (m_bShowPanel != value)
			{
				m_bShowPanel = value;
				if (Panel != null)
				{
					Panel.Visible = m_bShowPanel && base.Checked;
				}
			}
		}
	}

	public ToolStripTabItem()
	{
		Padding = new Padding(1);
		base.CheckOnClick = !base.Checked;
	}

	protected override void Dispose(bool disposing)
	{
		Panel = null;
		base.Dispose(disposing);
	}

	protected override void OnCheckStateChanged(EventArgs e)
	{
		base.OnCheckStateChanged(e);
		base.CheckOnClick = !base.Checked;
	}

	protected override void OnTextChanged(EventArgs e)
	{
		base.OnTextChanged(e);
		Panel.Text = Text;
	}

	void IShortcutSupport.ProcessShortcut()
	{
		base.Checked = true;
	}

	AttributeCollection ICustomTypeDescriptor.GetAttributes()
	{
		return TypeDescriptor.GetAttributes(this, noCustomTypeDesc: true);
	}

	string ICustomTypeDescriptor.GetClassName()
	{
		return TypeDescriptor.GetClassName(this, noCustomTypeDesc: true);
	}

	string ICustomTypeDescriptor.GetComponentName()
	{
		return TypeDescriptor.GetComponentName(this, noCustomTypeDesc: true);
	}

	TypeConverter ICustomTypeDescriptor.GetConverter()
	{
		return TypeDescriptor.GetConverter(this, noCustomTypeDesc: true);
	}

	EventDescriptor ICustomTypeDescriptor.GetDefaultEvent()
	{
		return TypeDescriptor.GetDefaultEvent(this, noCustomTypeDesc: true);
	}

	PropertyDescriptor ICustomTypeDescriptor.GetDefaultProperty()
	{
		return TypeDescriptor.GetDefaultProperty(this, noCustomTypeDesc: true);
	}

	object ICustomTypeDescriptor.GetEditor(Type editorBaseType)
	{
		return TypeDescriptor.GetEditor(this, editorBaseType, noCustomTypeDesc: true);
	}

	EventDescriptorCollection ICustomTypeDescriptor.GetEvents()
	{
		return TypeDescriptor.GetEvents(this, noCustomTypeDesc: true);
	}

	EventDescriptorCollection ICustomTypeDescriptor.GetEvents(Attribute[] attributes)
	{
		return TypeDescriptor.GetEvents(this, attributes, noCustomTypeDesc: true);
	}

	PropertyDescriptorCollection ICustomTypeDescriptor.GetProperties()
	{
		return GetProperties(TypeDescriptor.GetProperties(this, noCustomTypeDesc: true));
	}

	PropertyDescriptorCollection ICustomTypeDescriptor.GetProperties(Attribute[] attributes)
	{
		return GetProperties(TypeDescriptor.GetProperties(this, attributes, noCustomTypeDesc: true));
	}

	object ICustomTypeDescriptor.GetPropertyOwner(PropertyDescriptor pd)
	{
		return this;
	}

	private PropertyDescriptorCollection GetProperties(PropertyDescriptorCollection pdCol)
	{
		List<PropertyDescriptor> list = new List<PropertyDescriptor>(pdCol.Count);
		foreach (PropertyDescriptor item in pdCol)
		{
			if (IsHidden(item.Name))
			{
				Attribute[] attributes = new Attribute[2]
				{
					new BrowsableAttribute(browsable: false),
					new DesignerSerializationVisibilityAttribute(DesignerSerializationVisibility.Hidden)
				};
				list.Add(new CustomDescriptor(item, attributes));
			}
			else
			{
				list.Add(item);
			}
		}
		return new PropertyDescriptorCollection(list.ToArray());
	}

	private static bool IsHidden(string sName)
	{
		int i = 0;
		for (int num = HiddenProperties.Length; i < num; i++)
		{
			if (sName == HiddenProperties[i])
			{
				return true;
			}
		}
		return false;
	}

	private bool ShouldSerializePadding()
	{
		return Padding.All != 1;
	}

	private new void ResetPadding()
	{
		Padding = new Padding(1);
	}

	private void OnPositionChanged(RibbonControlAdvHeader header, int position)
	{
		header.InsertMainItem(this, position);
	}
}
