using System;
using System.ComponentModel;
using System.Drawing;
using System.Windows.Forms;
using System.Windows.Forms.Design;

namespace Syncfusion.Windows.Forms.Tools;

[ToolStripItemDesignerAvailability(ToolStripItemDesignerAvailability.None)]
internal class ToolStripMenuButton : ToolStripDropDownButton
{
	[ToolboxItem(false)]
	private class Office2007MenuStrip : ToolStripDropDown
	{
		private ToolStripPanelItem m_panel;

		public Office2007MenuStrip()
		{
			m_panel = new ToolStripPanelItem();
			m_panel.ToolStrip.ShowCaption = false;
			m_panel.ToolStrip.BorderStyle = ToolStripBorderStyle.Default;
			Items.Add(m_panel);
		}
	}

	public override bool HasDropDownItems => true;

	protected override Point DropDownLocation
	{
		get
		{
			Point dropDownLocation = base.DropDownLocation;
			if (base.DropDown is MenuDropDown { Borders: var borders } menuDropDown)
			{
				int num = borders.Top - 4;
				if (num > 0)
				{
					dropDownLocation.Y -= num;
				}
				if (base.Parent is RibbonControlAdvHeader { RightToLeft: RightToLeft.Yes } ribbonControlAdvHeader)
				{
					dropDownLocation.X = ribbonControlAdvHeader.PointToScreen(new Point(Bounds.X + base.Width - menuDropDown.Width)).X + 1;
				}
			}
			return dropDownLocation;
		}
	}

	public ToolStripMenuButton(RibbonControlAdvHeader parent)
	{
		base.Parent = parent;
	}

	protected override ToolStripDropDown CreateDefaultDropDown()
	{
		return new MenuDropDown(this);
	}

	protected override void OnDropDownShow(EventArgs e)
	{
		base.OnDropDownShow(e);
		ToolStripDropDown toolStripDropDown = base.DropDown;
		if (toolStripDropDown != null)
		{
			ToolStrip currentParent = GetCurrentParent();
			if (currentParent != null)
			{
				base.DropDown.Renderer = currentParent.Renderer;
			}
			if (toolStripDropDown.IsAutoGenerated && base.DropDownItems.Count == 0)
			{
				toolStripDropDown.OwnerItem = this;
				toolStripDropDown.Location = DropDownLocation;
				toolStripDropDown.Show();
				Invalidate();
			}
		}
	}
}
