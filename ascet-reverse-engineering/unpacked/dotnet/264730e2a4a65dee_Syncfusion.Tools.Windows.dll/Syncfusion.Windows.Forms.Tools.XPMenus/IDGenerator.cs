namespace Syncfusion.Windows.Forms.Tools.XPMenus;

internal class IDGenerator
{
	public static string GetNextID(string currentID)
	{
		string[] array = currentID.Split('_');
		if (array.Length > 1)
		{
			string s = array[array.Length - 1];
			try
			{
				int num = int.Parse(s);
				num++;
				int length = currentID.LastIndexOf('_');
				string text = currentID.Substring(0, length);
				return text + "_" + num;
			}
			catch
			{
			}
		}
		return currentID + "_1";
	}

	public static bool IsAutoGeneratedID(string ID)
	{
		if (ID.Length < 2)
		{
			return false;
		}
		if (ID[0] == '_')
		{
			string s = ID.Substring(1);
			int num = -1;
			try
			{
				num = int.Parse(s);
			}
			catch
			{
			}
			if (num != -1)
			{
				return true;
			}
		}
		return false;
	}
}
