internal class ToolStripPanelItemDesigner : IDesigner, IDisposable
{
	private class PanelItemSerializationService : ComponentSerializationService
	{
		private ComponentSerializationService m_baseService;

		public PanelItemSerializationService(ComponentSerializationService baseService)
		{
			m_baseService = baseService;
		}

		public override SerializationStore CreateStore()
		{
			return m_baseService.CreateStore();
		}

		public override ICollection Deserialize(SerializationStore store)
		{
			return m_baseService.Deserialize(store);
		}

		public override ICollection Deserialize(SerializationStore store, IContainer container)
		{
			ICollection items = m_baseService.Deserialize(store, container);
			return RemovePanelItems(items);
		}

		public override void DeserializeTo(SerializationStore store, IContainer container, bool validateRecycledTypes, bool applyDefaults)
		{
			m_baseService.DeserializeTo(store, container, validateRecycledTypes, applyDefaults);
		}

		public override SerializationStore LoadStore(Stream stream)
		{
			return m_baseService.LoadStore(stream);
		}

		public override void Serialize(SerializationStore store, object value)
		{
			m_baseService.Serialize(store, value);
			if (value is ToolStripPanelItem toolStripPanelItem)
			{
				SerializePanelItems(store, toolStripPanelItem.Items);
			}
		}

		public override void SerializeAbsolute(SerializationStore store, object value)
		{
			m_baseService.SerializeAbsolute(store, value);
		}

		public override void SerializeMember(SerializationStore store, object owningObject, MemberDescriptor member)
		{
			m_baseService.SerializeMember(store, owningObject, member);
		}

		public override void SerializeMemberAbsolute(SerializationStore store, object owningObject, MemberDescriptor member)
		{
			m_baseService.SerializeMemberAbsolute(store, owningObject, member);
		}

		private void SerializePanelItems(SerializationStore store, ICollection items)
		{
			foreach (ToolStripItem item in items)
			{
				m_baseService.Serialize(store, item);
				if (item is ToolStripPanelItem toolStripPanelItem)
				{
					SerializePanelItems(store, toolStripPanelItem.Items);
				}
				else if (item is ToolStripDropDownItem toolStripDropDownItem && toolStripDropDownItem.DropDown.IsAutoGenerated)
				{
					SerializePanelItems(store, toolStripDropDownItem.DropDownItems);
				}
			}
		}

		private ICollection RemovePanelItems(ICollection items)
		{
			ArrayList arrayList = new ArrayList(items);
			ICollection panelItems = GetPanelItems(items);
			foreach (ToolStripPanelItem item in panelItems)
			{
				RemovePanelItems(arrayList, item.Items);
			}
			return arrayList;
		}

		private void RemovePanelItems(ArrayList items, ICollection panelItems)
		{
			foreach (ToolStripItem panelItem in panelItems)
			{
				items.Remove(panelItem);
				if (panelItem is ToolStripDropDownItem toolStripDropDownItem && toolStripDropDownItem.DropDown.IsAutoGenerated)
				{
					RemovePanelItems(items, toolStripDropDownItem.DropDownItems);
				}
			}
		}

		private ICollection GetPanelItems(ICollection items)
		{
			ArrayList arrayList = new ArrayList();
			foreach (object item in items)
			{
				if (item is ToolStripPanelItem)
				{
					arrayList.Add(item);
				}
			}
			return arrayList;
		}
	}

	protected IComponent m_component;

	private static DTE s_dte;

	private static WindowEvents s_winEvents;

	private static DTEEvents s_dteEvents;

	IComponent IDesigner.Component => m_component;

	DesignerVerbCollection IDesigner.Verbs => null;

	void IDesigner.Initialize(IComponent component)
	{
		m_component = component;
		if (component == null)
		{
			return;
		}
		ToolStripExService toolStripExService = ToolStripExService.Get(component.Site);
		if (toolStripExService != null)
		{
			if (toolStripExService.Designers != null)
			{
				Type type = Type.GetType("System.Windows.Forms.Design.ToolStripItemDesigner, System.Design");
				if (type != null && Activator.CreateInstance(type) is ComponentDesigner componentDesigner)
				{
					toolStripExService.Designers[component] = componentDesigner;
					componentDesigner.Initialize(component);
				}
			}
			toolStripExService.AddItem(component as ToolStripPanelItem);
		}
		UpdateSerializationService(component);
		InitDTE();
	}

	void IDesigner.DoDefaultAction()
	{
	}

	void IDisposable.Dispose()
	{
		m_component = null;
	}

	public static void UpdateSerializationService(IComponent component)
	{
		if (component.Site != null)
		{
			IServiceProvider site = component.Site;
			UpdateSerializationService(site);
		}
	}

	public static void UpdateSerializationService(IServiceProvider serviceProvider)
	{
		if (serviceProvider.GetService(typeof(IServiceContainer)) is IServiceContainer serviceContainer)
		{
			Type typeFromHandle = typeof(ComponentSerializationService);
			if (serviceContainer.GetService(typeFromHandle) is ComponentSerializationService componentSerializationService && !(componentSerializationService is PanelItemSerializationService))
			{
				serviceContainer.RemoveService(typeFromHandle);
				serviceContainer.AddService(typeFromHandle, new PanelItemSerializationService(componentSerializationService));
			}
		}
	}

	private static void InitDTE()
	{
		//IL_004d: Unknown result type (might be due to invalid IL or missing references)
		//IL_0057: Expected O, but got Unknown
		//IL_0063: Unknown result type (might be due to invalid IL or missing references)
		//IL_006d: Expected O, but got Unknown
		//IL_0079: Unknown result type (might be due to invalid IL or missing references)
		//IL_0083: Expected O, but got Unknown
		if (s_dte == null)
		{
			s_dte = GetCurrentDTE();
			if (s_dte != null)
			{
				s_dteEvents = ((_DTE)s_dte).Events.DTEEvents;
				s_winEvents = ((_DTE)s_dte).Events[(Window)null];
				((_dispDTEEvents_Event)s_dteEvents).OnBeginShutdown += new _dispDTEEvents_OnBeginShutdownEventHandler(s_dteEvents_OnBeginShutdown);
				((_dispWindowEvents_Event)s_winEvents).WindowCreated += new _dispWindowEvents_WindowCreatedEventHandler(winEvents_WindowCreated);
				((_dispWindowEvents_Event)s_winEvents).WindowActivated += new _dispWindowEvents_WindowActivatedEventHandler(winEvents_WindowActivated);
			}
		}
	}

	private static void s_dteEvents_OnBeginShutdown()
	{
		//IL_000c: Unknown result type (might be due to invalid IL or missing references)
		//IL_0016: Expected O, but got Unknown
		//IL_0022: Unknown result type (might be due to invalid IL or missing references)
		//IL_002c: Expected O, but got Unknown
		//IL_0038: Unknown result type (might be due to invalid IL or missing references)
		//IL_0042: Expected O, but got Unknown
		((_dispDTEEvents_Event)s_dteEvents).OnBeginShutdown -= new _dispDTEEvents_OnBeginShutdownEventHandler(s_dteEvents_OnBeginShutdown);
		((_dispWindowEvents_Event)s_winEvents).WindowCreated -= new _dispWindowEvents_WindowCreatedEventHandler(winEvents_WindowCreated);
		((_dispWindowEvents_Event)s_winEvents).WindowActivated -= new _dispWindowEvents_WindowActivatedEventHandler(winEvents_WindowActivated);
		s_dte = null;
		s_dteEvents = null;
		s_winEvents = null;
	}

	private static void winEvents_WindowActivated(Window GotFocus, Window LostFocus)
	{
		ActivateDesignSerializationService(GotFocus);
	}

	private static void winEvents_WindowCreated(Window Window)
	{
		ActivateDesignSerializationService(Window);
	}

	private static void ActivateDesignSerializationService(Window Window)
	{
		if (Window.Object is IServiceProvider serviceProvider)
		{
			UpdateSerializationService(serviceProvider);
		}
	}

	private static DTE GetCurrentDTE()
	{
		IRunningObjectTable prot = null;
		IEnumMoniker ppenumMoniker = null;
		IBindCtx ppbc = null;
		IMoniker[] array = new IMoniker[1];
		string ppszDisplayName = null;
		object ppunkObject = null;
		Process currentProcess = Process.GetCurrentProcess();
		string value = currentProcess.Id.ToString();
		Syncfusion.Runtime.InteropServices.NativeMethods.GetRunningObjectTable(0, out prot);
		prot.EnumRunning(out ppenumMoniker);
		ppenumMoniker.Reset();
		DTE result = null;
		while (ppenumMoniker.Next(1, array, IntPtr.Zero) == 0)
		{
			Syncfusion.Runtime.InteropServices.NativeMethods.CreateBindCtx(0, out ppbc);
			array[0].GetDisplayName(ppbc, null, out ppszDisplayName);
			prot.GetObject(array[0], out ppunkObject);
			if (ppszDisplayName.StartsWith("!VisualStudio.DTE.") && ppszDisplayName.EndsWith(value))
			{
				result = (DTE)((ppunkObject is DTE) ? ppunkObject : null);
				break;
			}
			SolutionClass val = (SolutionClass)((ppunkObject is SolutionClass) ? ppunkObject : null);
			if (val != null)
			{
				int hWnd = ((_DTE)val.DTE).MainWindow.HWnd;
				GetWindowThreadProcessId((IntPtr)hWnd, out var lpdwProcessId);
				if (lpdwProcessId == currentProcess.Id)
				{
					result = val.DTE;
					break;
				}
			}
		}
		return result;
	}

	[DllImport("user32.dll")]
	private static extern uint GetWindowThreadProcessId(IntPtr hwnd, out uint lpdwProcessId);
}
