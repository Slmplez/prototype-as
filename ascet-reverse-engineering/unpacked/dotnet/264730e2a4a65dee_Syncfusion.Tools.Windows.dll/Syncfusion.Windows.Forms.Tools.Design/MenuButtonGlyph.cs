using System.ComponentModel;
using System.ComponentModel.Design;
using System.Drawing;
using System.Windows.Forms;
using System.Windows.Forms.Design.Behavior;

namespace Syncfusion.Windows.Forms.Tools.Design;

internal class MenuButtonGlyph : Glyph
{
	private class MenuButtonBehavior : Behavior
	{
		public override bool OnMouseDown(Glyph g, MouseButtons button, Point mouseLoc)
		{
			bool result = false;
			if (g is MenuButtonGlyph { Bounds: var bounds } menuButtonGlyph && bounds.Contains(mouseLoc))
			{
				ToolStripDropDownItem item = menuButtonGlyph.Item;
				if (item != null)
				{
					ToolStripDropDown dropDown = item.DropDown;
					if (!dropDown.Visible)
					{
						if (dropDown.IsAutoGenerated)
						{
							item.ShowDropDown();
						}
						else
						{
							menuButtonGlyph.m_selectionSvc.SetSelectedComponents(new IComponent[1] { dropDown }, SelectionTypes.Replace);
						}
					}
					else if (dropDown.IsAutoGenerated)
					{
						menuButtonGlyph.m_selectionSvc.SetSelectedComponents(new IComponent[1] { dropDown });
					}
				}
				result = true;
			}
			return result;
		}
	}

	private RibbonControlAdv m_control;

	private BehaviorService m_behaviorSvc;

	private ISelectionService m_selectionSvc;

	public override Rectangle Bounds
	{
		get
		{
			Rectangle result = Rectangle.Empty;
			if (m_behaviorSvc != null && m_control != null && m_control.Visible)
			{
				RibbonControlAdvHeader headerInternal = m_control.HeaderInternal;
				if (headerInternal != null)
				{
					ToolStripItem menuButton = headerInternal.MenuButton;
					if (menuButton.Visible)
					{
						result = menuButton.Bounds;
						result.Location = m_behaviorSvc.MapAdornerWindowPoint(headerInternal.Handle, result.Location);
					}
				}
			}
			return result;
		}
	}

	private ToolStripDropDownItem Item => m_control.HeaderInternal.MenuButton;

	public MenuButtonGlyph(RibbonControlAdv control)
		: base(new MenuButtonBehavior())
	{
		m_control = control;
		m_behaviorSvc = DesignerUtils.GetBehaviorService(control);
		m_selectionSvc = DesignerUtils.GetSelectionService(control);
	}

	public override Cursor GetHitTest(Point p)
	{
		if (m_control != null && m_control.Visible && Bounds.Contains(p))
		{
			return Cursors.Hand;
		}
		return null;
	}

	public override void Paint(PaintEventArgs pe)
	{
	}
}
