using System;
using System.ComponentModel;
using System.Globalization;
using System.Windows.Forms;

namespace Syncfusion.Windows.Forms.Tools.Design;

internal class MenuDropDownTypeConverter : ReferenceConverter
{
	public MenuDropDownTypeConverter(Type type)
		: base(type)
	{
	}

	public override object ConvertTo(ITypeDescriptorContext context, CultureInfo culture, object value, Type destinationType)
	{
		if (destinationType == typeof(string) && value is ToolStripDropDown { IsAutoGenerated: not false })
		{
			return null;
		}
		return base.ConvertTo(context, culture, value, destinationType);
	}

	protected override bool IsValueAllowed(ITypeDescriptorContext context, object value)
	{
		if (value is ToolStripDropDown { IsAutoGenerated: not false })
		{
			return false;
		}
		return base.IsValueAllowed(context, value);
	}
}
